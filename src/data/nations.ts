export function getNationCode(nationality: string): string {
  if (!nationality) return "un";
  const trimmed = nationality.trim();
  if (NATION_CODES[trimmed]) return NATION_CODES[trimmed];
  if (ALIAS_MAP[trimmed]) return ALIAS_MAP[trimmed];
  const lower = trimmed.toLowerCase();
  for (const [key, code] of Object.entries(NATION_CODES)) {
    if (key.toLowerCase() === lower || code === lower) return code;
  }
  return "un";
}

export function getNationFlagUrl(nationality: string): string {
  const code = getNationCode(nationality);
  return `https://cdn.jsdelivr.net/gh/lipis/flag-icons@7.3.2/flags/4x3/${code}.svg`;
}

export function getClubCrestUrl(clubId: string, variant: 'default' | 'underscore' | 'clean' = 'default'): string {
  const slug = variant === 'underscore'
    ? clubId.replace(/-/g, '_')
    : variant === 'clean'
      ? clubId.replace(/[-_]/g, '')
      : clubId;
  return `https://cdn.jsdelivr.net/gh/miguelholy56/logos-clubes@main/logos/${slug}.png`;
}
